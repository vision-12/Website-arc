#!/usr/bin/env node
/**
 * Generates src/lib/fonts/fallbacks.css: metric-matched fallback faces for the allow-listed
 * families on systems without Arial or Times New Roman.
 *
 * Why: next/font's own fallback faces use local(Arial) and local(Times New Roman). Android phones
 * (the primary device, MP §1) and Linux have neither, so while a web font downloads they show an
 * unadjusted system font, and the text jumps when the web font arrives (layout shift). These
 * faces do the same adjustment against the fonts those systems do have: Roboto and Noto Serif on
 * Android, DejaVu Sans and DejaVu Serif on Linux.
 *
 * Metrics: web fonts and Android fonts from Next's capsize table (node_modules/next/dist/server/
 * capsize-font-metrics.json). DejaVu is not in that table; its average width was measured from
 * the installed TTFs with the same letter-frequency weighting (fontTools) and scaled by 1.0059,
 * the mean ratio between capsize and that measurement over six of our families.
 * Formula: Next's calculateFallbackFontValues (size-adjust from average character width).
 *
 * Run: node scripts/generate-font-fallbacks.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const capsize = JSON.parse(
  readFileSync(
    new URL('../node_modules/next/dist/server/capsize-font-metrics.json', import.meta.url),
  ),
);

const FAMILIES = [
  ['Inter', 'inter', 'sans'],
  ['Source Serif 4', 'sourceSerif4', 'serif'],
  ['Playfair Display', 'playfairDisplay', 'serif'],
  ['Lora', 'lora', 'serif'],
  ['Nunito Sans', 'nunitoSans', 'sans'],
  ['Merriweather', 'merriweather', 'serif'],
  ['DM Sans', 'dMSans', 'sans'],
  ['Libre Baskerville', 'libreBaskerville', 'serif'],
];

const FALLBACKS = {
  sans: [
    {
      suffix: 'Android',
      local: ['Roboto', 'Roboto Regular', 'Roboto-Regular'],
      metrics: capsize.roboto,
    },
    {
      suffix: 'Linux',
      local: ['DejaVu Sans', 'DejaVuSans'],
      metrics: { unitsPerEm: 2048, xWidthAvg: 1037 * 1.0059 },
    },
  ],
  serif: [
    {
      suffix: 'Android',
      local: ['Noto Serif', 'NotoSerif', 'NotoSerif-Regular'],
      metrics: capsize.notoSerif,
    },
    {
      suffix: 'Linux',
      local: ['DejaVu Serif', 'DejaVuSerif'],
      metrics: { unitsPerEm: 2048, xWidthAvg: 1048 * 1.0059 },
    },
  ],
};

// Two decimals, written the way Prettier writes CSS numbers (0.00 → 0, 90.40 → 90.4), so the
// committed file stays byte-identical after the pre-commit formatter runs.
const pct = (n) => `${Number((n * 100).toFixed(2))}%`;

/** Next's calculateFallbackFontValues: overrides that make `fallback` take `main`'s space. */
export function fallbackOverrides(main, fallback) {
  const sizeAdjust = main.xWidthAvg / main.unitsPerEm / (fallback.xWidthAvg / fallback.unitsPerEm);
  const per = main.unitsPerEm * sizeAdjust;
  return {
    ascentOverride: pct(main.ascent / per),
    descentOverride: pct(Math.abs(main.descent) / per),
    lineGapOverride: pct(main.lineGap / per),
    sizeAdjust: pct(sizeAdjust),
  };
}

export function fallbackCss() {
  const blocks = [];
  for (const [family, key, category] of FAMILIES) {
    const main = capsize[key];
    if (!main) throw new Error(`No capsize metrics for ${family}`);
    for (const fallback of FALLBACKS[category]) {
      const o = fallbackOverrides(main, fallback.metrics);
      blocks.push(
        [
          '@font-face {',
          `  font-family: '${family} Fallback ${fallback.suffix}';`,
          `  src: ${fallback.local.map((n) => `local('${n}')`).join(', ')};`,
          `  ascent-override: ${o.ascentOverride};`,
          `  descent-override: ${o.descentOverride};`,
          `  line-gap-override: ${o.lineGapOverride};`,
          `  size-adjust: ${o.sizeAdjust};`,
          '}',
        ].join('\n'),
      );
    }
  }
  const header =
    '/* Generated by scripts/generate-font-fallbacks.mjs; do not edit. Metric-matched fallback faces\n' +
    ' * for Android (Roboto, Noto Serif) and Linux (DejaVu), so a web font arriving late does not move\n' +
    ' * the text. next/font covers systems with Arial and Times New Roman. */\n';
  return `${header}${blocks.join('\n')}\n`;
}

export { capsize };

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(new URL('../src/lib/fonts/fallbacks.css', import.meta.url), fallbackCss());
  console.log(`wrote ${FAMILIES.length * 2} fallback faces`);
}
