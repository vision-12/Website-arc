'use client';
import { useActionState, useEffect, useState } from 'react';
import { confirmMfaEnrolment, startMfaEnrolment, type EnrolmentStart } from '../actions';
import { IDLE } from '../schema';
import { Field, FormMessage, SubmitButton } from './form-parts';

/** TOTP enrolment: QR code (with the key written out for those who can't scan), then a code to confirm. */
export function MfaSetup({ next }: { next: string }) {
  const [enrolment, setEnrolment] = useState<EnrolmentStart | null>(null);
  const [state, action] = useActionState(confirmMfaEnrolment, IDLE);

  useEffect(() => {
    let cancelled = false;
    void startMfaEnrolment().then((r) => {
      if (!cancelled) setEnrolment(r);
    });
    return () => {
      cancelled = true;
    };
  }, []);

  if (!enrolment)
    return (
      <p role="status" className="text-sm text-muted-foreground">
        Preparing your setup code…
      </p>
    );
  if (!enrolment.ok || !enrolment.factorId) {
    return (
      <p role="alert" className="text-sm text-destructive">
        {enrolment.message ?? 'Something went wrong. Please reload the page.'}
      </p>
    );
  }

  return (
    <div className="space-y-6">
      <ol className="list-decimal space-y-2 pl-5 text-sm">
        <li>
          Install an authenticator app on your phone, such as Google Authenticator or Microsoft
          Authenticator.
        </li>
        <li>In the app, add an account and scan this code.</li>
        <li>Type the 6-digit code the app shows.</li>
      </ol>
      {enrolment.qrCode ? (
        // eslint-disable-next-line @next/next/no-img-element -- data: URL SVG generated by Supabase; not an optimisable image
        <img
          src={enrolment.qrCode}
          alt="QR code to add this account to your authenticator app"
          width={192}
          height={192}
          className="mx-auto rounded-md border bg-white p-2"
        />
      ) : null}
      <div className="text-sm">
        <p className="font-medium">Can&apos;t scan the code?</p>
        <p className="text-muted-foreground">
          Choose &quot;enter a setup key&quot; in the app and type:
        </p>
        <p
          className="mt-1 rounded-md bg-muted px-3 py-2 font-mono text-sm break-all"
          data-testid="totp-secret"
        >
          {enrolment.secret}
        </p>
      </div>
      <form action={action} className="space-y-4" noValidate>
        <FormMessage state={state} />
        <input type="hidden" name="factorId" value={enrolment.factorId} />
        <input type="hidden" name="next" value={next} />
        <Field
          name="code"
          label="6-digit code"
          inputMode="numeric"
          autoComplete="one-time-code"
          errors={state.fieldErrors?.code}
        />
        <SubmitButton pendingLabel="Checking…">Turn on two-step sign-in</SubmitButton>
      </form>
    </div>
  );
}
